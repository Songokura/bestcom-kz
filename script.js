  /* ---------- делегированные клики по контактам ---------- */
  function handleContactClick(e) {
    var a = e.target.closest('a[data-ch], a[href^="tel:"], a[href^="mailto:"], a[href*="wa.me"]');
    if (!a) return;
    var ch = a.getAttribute('data-ch');
    if (!ch) {
      var href = a.getAttribute('href') || '';
      ch = href.indexOf('wa.me') > -1 ? 'whatsapp'
         : href.indexOf('tel:') === 0 ? 'tel'
         : href.indexOf('mailto:') === 0 ? 'email' : 'other';
    }
    var sec = a.closest('section');
    trackEvent('contact_click', {
      channel: ch,
      contact: a.getAttribute('data-contact') || '',
      section: sec ? (sec.id || (sec.className || '').split(' ')[0]) : '',
      lang: currentLang
    });
  }
  document.addEventListener('click', handleContactClick);

  /* ---------- видеоотзывы: фасад вместо трёх плееров ----------
     До клика в DOM нет ни одного iframe — YouTube тянет ~500 КБ на плеер,
     а отзывы лежат глубоко на странице и до них доходят не все.
     По клику плитка заменяется на плеер с autoplay и уходит событие
     review_play — на этапе Google Ads его можно считать микроконверсией. */
  document.querySelectorAll('.vrev__media').forEach(function (box) {
    var btn = box.querySelector('.vrev__play');
    if (!btn) return;
    btn.addEventListener('click', function () {
      var id = box.getAttribute('data-yt');
      if (!id) return;
      var fr = document.createElement('iframe');
      fr.src = 'https://www.youtube-nocookie.com/embed/' + id +
               '?autoplay=1&rel=0&modestbranding=1&playsinline=1';
      fr.title = btn.getAttribute('aria-label') || 'Видеоотзыв о внедрении Bitrix24';
      fr.allow = 'accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share';
      fr.setAttribute('allowfullscreen', '');
      fr.setAttribute('loading', 'lazy');
      box.classList.add('is-live');
      btn.remove();
      box.appendChild(fr);
      trackEvent('review_play', { video: id, lang: currentLang });
    });
  });

  /* ---------- год в подвале ---------- */
  var y = document.getElementById('year');
  if (y) y.textContent = String(new Date().getFullYear());
