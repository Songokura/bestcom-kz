  /* Русские строки снимаем с разметки один раз — она и есть RU-версия */
  var RU = { html: {}, alt: {}, ph: {}, aria: {} };
  var currentLang = 'ru';

  function captureRU() {
    document.querySelectorAll('[data-i]').forEach(function (el) {
      RU.html[el.getAttribute('data-i')] = el.innerHTML;
    });
    document.querySelectorAll('[data-i-alt]').forEach(function (el) {
      RU.alt[el.getAttribute('data-i-alt')] = el.getAttribute('alt') || '';
    });
    document.querySelectorAll('[data-i-ph]').forEach(function (el) {
      RU.ph[el.getAttribute('data-i-ph')] = el.getAttribute('placeholder') || '';
    });
    document.querySelectorAll('[data-i-aria]').forEach(function (el) {
      RU.aria[el.getAttribute('data-i-aria')] = el.getAttribute('aria-label') || '';
    });
  }

  function applyLang(lang) {
    currentLang = lang;
    var dict = lang === 'kz' ? KZ : null;
    document.querySelectorAll('[data-i]').forEach(function (el) {
      var k = el.getAttribute('data-i');
      var v = dict ? dict[k] : RU.html[k];
      if (v == null) v = RU.html[k];           /* нет перевода → русский оригинал */
      if (v != null && el.innerHTML !== v) el.innerHTML = v;
    });
    document.querySelectorAll('[data-i-alt]').forEach(function (el) {
      var k = el.getAttribute('data-i-alt');
      var v = (dict && dict[k]) || RU.alt[k];
      if (v != null) el.setAttribute('alt', v);
    });
    document.querySelectorAll('[data-i-ph]').forEach(function (el) {
      var k = el.getAttribute('data-i-ph');
      var v = (dict && dict[k]) || RU.ph[k];
      if (v != null) el.setAttribute('placeholder', v);
    });
    document.querySelectorAll('[data-i-aria]').forEach(function (el) {
      var k = el.getAttribute('data-i-aria');
      var v = (dict && dict[k]) || RU.aria[k];
      if (v != null) el.setAttribute('aria-label', v);
    });

    var meta = META[lang];
    document.documentElement.setAttribute('lang', meta.lang);
    document.title = meta.title;
    var md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', meta.desc);

    document.querySelectorAll('.lang__btn').forEach(function (b) {
      var on = b.getAttribute('data-lang') === lang;
      b.classList.toggle('is-active', on);
      b.setAttribute('aria-pressed', on ? 'true' : 'false');
    });
    try { localStorage.setItem('bestcom-lang', lang); } catch (e) {}
  }

  function initLang() {
    captureRU();
    var saved = null;
    try { saved = localStorage.getItem('bestcom-lang'); } catch (e) {}
    if (saved === 'kz') applyLang('kz'); else applyLang('ru');
    document.querySelectorAll('.lang__btn').forEach(function (b) {
      b.addEventListener('click', function () {
        var l = b.getAttribute('data-lang');
        if (l !== currentLang) applyLang(l);
      });
    });
  }
  initLang();


